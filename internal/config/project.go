package config

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

// ProjectTemplate returns a self-documenting project config. forgeType and repo are the forge detected
// from the git origin (see provider.Forge); an empty forgeType means none was detected.
//
// Only the forge provider is active: the project file overlays the global config per field and per name,
// so any other uncommented line would override the user's global settings, views or actions.
func ProjectTemplate(forgeType, repo string) string {
	var b strings.Builder
	b.WriteString(projectHead)
	if forgeType == "" {
		b.WriteString(`# The git origin could not be detected (not a git repository, or no "origin" remote), so this block is
# commented out and the global "forge" provider stays in use. Uncomment it and set type and project:
# [provider.forge]
# type = "github"
# project = "owner/repo"
`)
	} else {
		fmt.Fprintf(&b, `# Detected from the git origin. "forge" is the provider the default global views use, so this replaces it.
# GitHub Enterprise hosts are detected as gitlab: set type = "github" for them.
[provider.forge]
type = %s
project = %s
`, strconv.Quote(forgeType), strconv.Quote(repo))
	}
	b.WriteString(projectTail)
	return b.String()
}

// InitProject writes ProjectTemplate(forgeType, repo) to dir/.lanes.toml and returns its path.
// It never overwrites: an existing file is an error wrapping fs.ErrExist.
func InitProject(dir, forgeType, repo string) (string, error) {
	path := filepath.Join(dir, ProjectFile)
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		if os.IsExist(err) {
			return path, fmt.Errorf("%s already exists: %w", ProjectFile, os.ErrExist)
		}
		return path, err
	}
	if _, err := f.WriteString(ProjectTemplate(forgeType, repo)); err != nil {
		f.Close()
		return path, err
	}
	return path, f.Close()
}

// OverwriteProject replaces dir/.lanes.toml with ProjectTemplate(forgeType, repo). With backup the old file is
// first renamed to .lanes.toml.bak, replacing an older backup.
func OverwriteProject(dir, forgeType, repo string, backup bool) (string, error) {
	path := filepath.Join(dir, ProjectFile)
	if backup {
		if err := os.Rename(path, path+".bak"); err != nil && !os.IsNotExist(err) {
			return path, err
		}
	}
	return path, os.WriteFile(path, []byte(ProjectTemplate(forgeType, repo)), 0o644)
}

const projectHead = `# lanes — project config (generated by "lanes init").
#
# This file overlays your global config (` + "`:config`" + ` prints its path); it does not replace it:
# [settings] and [theme] merge per field, [keymap] per key, [provider.<name>] and [action.<name>] by name
# (as a whole), [[view]] by name (same name replaces, new names are appended). So everything you do not
# need here stays commented out. Reference: https://github.com/chriha/lanes#configuration

# ---------------------------------------------------------------------------------------------------------
# Providers produce the items of a view: [provider.<name>], referenced by a view's provider = "<name>".
#
# type     gitlab         open merge requests, via the glab CLI
#          github         open pull requests, via the gh CLI (also for GitHub Enterprise)
#          github-issues  open issues, via the gh CLI
#          linear         a Linear team's open issues
#          auto           github for a github.com origin, gitlab for any other host
#          command        any shell command printing a JSON array of items
# project  gitlab: group/project, github/github-issues: owner/repo; default: detected from the git origin
# command  command: the shell command (run through $SHELL -c)
# team     linear: the team key, e.g. ENG (required)
# token_env  linear: env var holding the API key (default LINEAR_API_KEY)
# https://github.com/chriha/lanes#providers
# ---------------------------------------------------------------------------------------------------------

`

